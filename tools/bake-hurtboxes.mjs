#!/usr/bin/env node
/* Bakes src/hurtboxes.js from the rig.

   Hurtboxes used to be computed from the rig's joint positions every frame,
   which quietly tied the art to the gameplay: nudging a joint to make a pose
   read better also moved the box that decides whether the fighter can be hit,
   and any such change is a simulation change that breaks netplay compatibility.

   This lifts the boxes out into their own table so the two can move
   independently. The numbers are DERIVED from the old formula rather than
   re-authored, so the split changes nothing — which the golden replays then
   confirm. Re-run it only to re-derive from a changed formula; day to day the
   table is edited directly, or left alone while the art changes around it.

     node tools/bake-hurtboxes.mjs
*/
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { openGame, ROOT } from "../tests/harness.mjs";

const { browser, page, errors } = await openGame();

const baked = await page.evaluate(() => {
  const out = {};
  for (const name in POSE){
    const p = POSE[name];
    const [hd0, hd1] = p.hd, [nk0, nk1] = p.nk, [pv0, pv1] = p.pv;
    const minX = Math.min(nk0, pv0), minY = Math.min(nk1, pv1), maxY = Math.max(nk1, pv1);
    out[name] = [
      /* head  */ [hd0 - 9, hd1 - 9, 18, 18, 0],
      /* torso */ [minX - 11, minY, Math.abs(nk0 - pv0) + 22, maxY - minY, 2],
      /* legs  */ [pv0 - 12, pv1, 24, -pv1, 1]
    ];
  }
  return out;
});
await browser.close();
if (errors.length){ console.error("Page errors:\n  " + errors.join("\n  ")); process.exit(1); }

const rows = Object.entries(baked)
  .map(([name, boxes]) => "  " + name.padEnd(11) + ": [" +
       boxes.map(b => "[" + b.join(",") + "]").join(", ") + "]")
  .join(",\n");

const file = `/* ============================================================================
   HURTBOXES — generated by tools/bake-hurtboxes.mjs, do not edit by hand
   ----------------------------------------------------------------------------
   One entry per pose, each holding the three boxes that can be hit: head,
   torso and legs. Extended limbs are deliberately not vulnerable — it keeps
   trades readable.

   Boxes are in rig space: x and y measured from the point between the feet
   with y negative upward, facing right, before the character's scale is
   applied. The fifth number is a height pad added AFTER scaling. It exists
   because the formula these were derived from added its last pixel or two
   unscaled, and preserving that quirk is what makes this table an exact
   substitute rather than a balance change. Worth straightening out one day,
   deliberately, with a version bump.

       [ x, y, width, height, unscaledHeightPad ]
   ========================================================================== */

const HURT = {
${rows}
};
/* A pose with no entry should be impossible — the bake covers every pose in
   the rig — but standing boxes are a safer failure than none at all. */
const HURT_FALLBACK = HURT.idle1;
`;

writeFileSync(resolve(ROOT, "src/hurtboxes.js"), file);
console.log("baked " + Object.keys(baked).length + " poses -> src/hurtboxes.js");
