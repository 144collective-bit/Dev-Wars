const GLYPH_ROWS = {};
for (const c in GLYPHS) GLYPH_ROWS[c] = GLYPHS[c].split("/");

function textWidth(str, sc=1, sp=1){ return str.length * (5 + sp) * sc - sp * sc; }

function drawText(ctx, str, x, y, color, sc=1, sp=1){
  str = String(str).toUpperCase();
  ctx.fillStyle = color;
  let cx = x;
  for (let i = 0; i < str.length; i++){
    const rows = GLYPH_ROWS[str[i]] || GLYPH_ROWS["?"];
    for (let r = 0; r < 7; r++){
      const row = rows[r];
      let run = -1;
      for (let c = 0; c <= 5; c++){
        const on = c < 5 && row[c] === "#";
        if (on && run < 0) run = c;
        else if (!on && run >= 0){ ctx.fillRect(cx + run*sc, y + r*sc, (c-run)*sc, sc); run = -1; }
      }
    }
    cx += (5 + sp) * sc;
  }
}
function drawTextC(ctx, str, cx, y, color, sc=1, sp=1){
  drawText(ctx, str, Math.round(cx - textWidth(String(str), sc, sp)/2), y, color, sc, sp);
}
function drawTextShadow(ctx, str, x, y, color, shadow, sc=1, sp=1){
  drawText(ctx, str, x + sc, y + sc, shadow, sc, sp);
  drawText(ctx, str, x, y, color, sc, sp);
}
